CREATE EXTENSION IF NOT EXISTS vector;
--;;
CREATE EXTENSION IF NOT EXISTS btree_gist;
--;;
CREATE TABLE users (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome        text        NOT NULL,
  email       text        NOT NULL UNIQUE,
  senha_hash  text        NOT NULL,
  papel       text        NOT NULL DEFAULT 'user' CHECK (papel IN ('user', 'admin')),
  criado_em   timestamptz NOT NULL DEFAULT now()
);
--;;
CREATE TABLE listings (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id         bigint           NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  titulo           text             NOT NULL,
  descricao        text             NOT NULL DEFAULT '',
  tipo             text             NOT NULL CHECK (tipo IN ('urbana', 'speed', 'mountain', 'hibrida', 'eletrica', 'infantil', 'dobravel')),
  aro              integer          CHECK (aro BETWEEN 12 AND 29),
  tamanho          text             CHECK (tamanho IN ('PP', 'P', 'M', 'G', 'GG')),
  diaria_centavos  integer          NOT NULL CHECK (diaria_centavos > 0),
  cidade           text             NOT NULL,
  lat              double precision,
  lng              double precision,
  status           text             NOT NULL DEFAULT 'publicado' CHECK (status IN ('publicado', 'pausado')),
  embedding        vector(768),
  criado_em        timestamptz      NOT NULL DEFAULT now()
);
--;;
CREATE INDEX listings_owner_idx ON listings (owner_id);
--;;
CREATE INDEX listings_cidade_idx ON listings (lower(cidade));
--;;
CREATE TABLE listing_photos (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  listing_id  bigint  NOT NULL REFERENCES listings (id) ON DELETE CASCADE,
  url         text    NOT NULL,
  ordem       integer NOT NULL DEFAULT 0
);
--;;
CREATE INDEX listing_photos_listing_idx ON listing_photos (listing_id, ordem);
--;;
CREATE TABLE availability_blocks (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  listing_id  bigint    NOT NULL REFERENCES listings (id) ON DELETE CASCADE,
  periodo     daterange NOT NULL CHECK (NOT isempty(periodo))
);
--;;
CREATE INDEX availability_blocks_periodo_idx ON availability_blocks USING gist (listing_id, periodo);
--;;
CREATE TABLE bookings (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  listing_id      bigint      NOT NULL REFERENCES listings (id) ON DELETE CASCADE,
  renter_id       bigint      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  periodo         daterange   NOT NULL CHECK (NOT isempty(periodo)),
  total_centavos  integer     NOT NULL CHECK (total_centavos > 0),
  status          text        NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'confirmed', 'completed', 'rejected', 'cancelled')),
  criado_em       timestamptz NOT NULL DEFAULT now(),
  -- Duas reservas confirmadas (ou concluídas) da mesma bike não podem se sobrepor.
  CONSTRAINT bookings_sem_sobreposicao
    EXCLUDE USING gist (listing_id WITH =, periodo WITH &&)
    WHERE (status IN ('confirmed', 'completed'))
);
--;;
CREATE INDEX bookings_renter_idx ON bookings (renter_id);
--;;
CREATE TABLE payments (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id      bigint      NOT NULL UNIQUE REFERENCES bookings (id) ON DELETE CASCADE,
  valor_centavos  integer     NOT NULL CHECK (valor_centavos > 0),
  status          text        NOT NULL CHECK (status IN ('captured', 'refunded')),
  criado_em       timestamptz NOT NULL DEFAULT now()
);
--;;
CREATE TABLE reviews (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id  bigint      NOT NULL REFERENCES bookings (id) ON DELETE CASCADE,
  autor_id    bigint      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  alvo        text        NOT NULL CHECK (alvo IN ('listing', 'owner', 'renter')),
  nota        smallint    NOT NULL CHECK (nota BETWEEN 1 AND 5),
  comentario  text        NOT NULL DEFAULT '',
  criado_em   timestamptz NOT NULL DEFAULT now(),
  -- Uma avaliação por reserva, por autor e por direção.
  UNIQUE (booking_id, autor_id, alvo)
);
--;;
-- EXCLUDE não cruza tabelas: estes dois triggers impedem que reservas confirmadas
-- e datas bloqueadas pelo dono se sobreponham. Usam o mesmo SQLSTATE da restrição
-- (exclusion_violation, 23P01) para a API responder 409 nos dois casos.
CREATE FUNCTION checar_reserva_vs_bloqueios() RETURNS trigger AS $$
BEGIN
  IF NEW.status IN ('confirmed', 'completed') AND EXISTS (
       SELECT 1 FROM availability_blocks b
        WHERE b.listing_id = NEW.listing_id
          AND b.periodo && NEW.periodo) THEN
    RAISE EXCEPTION 'A reserva cai em datas bloqueadas pelo dono'
      USING ERRCODE = 'exclusion_violation';
  END IF;
  RETURN NEW;
END
$$ LANGUAGE plpgsql;
--;;
CREATE TRIGGER bookings_vs_bloqueios
  BEFORE INSERT OR UPDATE OF status, periodo, listing_id ON bookings
  FOR EACH ROW EXECUTE FUNCTION checar_reserva_vs_bloqueios();
--;;
CREATE FUNCTION checar_bloqueio_vs_reservas() RETURNS trigger AS $$
BEGIN
  IF EXISTS (
       SELECT 1 FROM bookings r
        WHERE r.listing_id = NEW.listing_id
          AND r.status IN ('confirmed', 'completed')
          AND r.periodo && NEW.periodo) THEN
    RAISE EXCEPTION 'O bloqueio cai em datas com reserva confirmada'
      USING ERRCODE = 'exclusion_violation';
  END IF;
  RETURN NEW;
END
$$ LANGUAGE plpgsql;
--;;
CREATE TRIGGER bloqueios_vs_bookings
  BEFORE INSERT OR UPDATE ON availability_blocks
  FOR EACH ROW EXECUTE FUNCTION checar_bloqueio_vs_reservas();
